<h1>Where this comes from</h1>
<p class="lede">
	Japan has a secondhand economy that most countries do not, and it is the reason this business
	works.
</p>

<h2>The resale chains</h2>
<p>
	Chains like Hard Off, Book Off, and Mode Off operate across the country, buying goods over the
	counter and reselling them graded and tested. Audio equipment, cameras, instruments, and
	tableware move through them constantly. Because the chains price for volume rather than for
	collectors, well-kept pieces routinely sit on shelves at prices that do not reflect what they are
	worth to a buyer abroad.
</p>

<h2>Flea markets and temple markets</h2>
<p>
	The monthly markets — Toji in Kyoto is the best known — are where textiles, ceramics, and smaller
	antiques surface. This is slower, less predictable sourcing, and it is where the genuinely
	unusual pieces come from.
</p>

<h2>Estate clearances</h2>
<p>
	Japan's population is aging, and a steady volume of well-maintained household goods enters resale
	channels through estate clearances. This is not a sad footnote to the business model; it is the
	supply. Formal tableware bought for guests and never used, kimono chests, boxed gift sets — the
	things a household keeps carefully and then no longer needs.
</p>

<h2>Mottainai</h2>
<p>
	The word is usually translated as "what a waste," but it carries more than that: a sense that
	something still useful should not be discarded. It is the idea behind boro textiles, mended until
	the mending became the object. It is also, straightforwardly, the argument for buying secondhand.
</p>

<h2>How we grade</h2>
<p>
	Every listing carries a condition grade and specific condition notes, not just a grade. Where a
	piece has been serviced — a replaced Walkman drive belt, replaced camera light seals — the
	listing says so. Where wear is visible, the listing says that too, and the price reflects it.
	Secondhand goods sold without honest condition notes generate returns, and returns across an
	ocean are the fastest way to lose money in this business.
</p>
